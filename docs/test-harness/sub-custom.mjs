import { launch, open } from './lib.mjs'
const b = await launch()
const { page, errors } = await open(b, { role: 'admin', path: '/admin/subscriptions', lang: 'ar', viewport: { width: 1280, height: 900 } })
await page.waitForTimeout(1500)
await page.getByRole('button', { name: /تجديد/ }).first().click()
await page.waitForTimeout(400)
const dlg = page.locator('form').last()
await dlg.getByRole('button', { name: /فترة مخصصة/ }).click()
await page.waitForTimeout(300)
const dates = dlg.locator('input[type=date]')
await dates.nth(0).fill('2026-12-01')
await dates.nth(1).fill('2026-11-01')
await page.waitForTimeout(200)
const err = await dlg.locator('[role=alert]').innerText().catch(() => null)
await page.screenshot({ path: 'sub-custom-error.png' })
await dates.nth(1).fill('2027-03-15')
await page.waitForTimeout(200)
await page.screenshot({ path: 'sub-custom-ok.png' })
await dlg.locator('button[type=submit]').click()
await page.waitForTimeout(800)
const seen = await fetch('http://127.0.0.1:3001/__seen').then(r => r.json())
console.log(JSON.stringify({ err, req: seen.filter(x => /subscription/.test(x.url)).map(x => [x.url, x.body]), errors }))
await b.close()
